export function parseTypeFaceJson(bytes: Uint8Array): IFontData | null {
  try {
    const parsed = JSON.parse(new TextDecoder().decode(bytes)) as Partial<IFontData>;
    if (
      !parsed ||
      typeof parsed.resolution !== "number" ||
      !parsed.boundingBox ||
      typeof parsed.boundingBox.yMin !== "number" ||
      typeof parsed.boundingBox.yMax !== "number" ||
      !parsed.glyphs ||
      typeof parsed.glyphs !== "object"
    ) {
      return null;
    }
    return {
      resolution: parsed.resolution,
      underlineThickness:
        typeof parsed.underlineThickness === "number"
          ? parsed.underlineThickness
          : 50,
      boundingBox: parsed.boundingBox,
      glyphs: parsed.glyphs,
    };
  } catch {
    return null;
  }
}
